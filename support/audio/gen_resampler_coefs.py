#!/usr/bin/env python3
"""
Generates target/pocket/audio_resampler_coefs.sv, the coefficient ROM for the
polyphase 32kHz -> 48kHz audio resampler (target/pocket/audio_resampler.sv).

Kernel: Kaiser windowed sinc, TAPS taps, PHASES phases per input sample.
Because the kernel is symmetric only phases 0..PHASES/2 are stored; the
resampler mirrors the rest: C[p][k] == C[PHASES-p][TAPS-1-k].

Each phase is normalized to exactly unity DC gain so the overall volume of
the core is unchanged.
"""
import math, os

TAPS = 32
PHASES = 64
CUTOFF = 0.47       # -6dB point as a fraction of the input (DSP) sample rate
BETA = 7.0          # Kaiser beta (~70dB stopband)
FRAC_BITS = 16      # coefficients are signed Q2.16
WIDTH = 18

def i0(x):
    s, t, k = 1.0, 1.0, 1
    while t > 1e-12 * s:
        t *= (x / (2 * k)) ** 2
        s += t
        k += 1
    return s

def h(t):
    half = TAPS / 2
    if abs(t) >= half:
        return 0.0
    x = 2 * CUTOFF * t
    sinc = 1.0 if x == 0 else math.sin(math.pi * x) / (math.pi * x)
    w = i0(BETA * math.sqrt(1 - (t / half) ** 2)) / i0(BETA)
    return 2 * CUTOFF * sinc * w

rows = []
for p in range(PHASES // 2 + 1):
    mu = p / PHASES
    c = [h(k + mu - TAPS / 2) for k in range(TAPS)]
    s = sum(c)
    q = [round(v / s * (1 << FRAC_BITS)) for v in c]
    # Fix rounding so each phase sums exactly to 1.0
    err = (1 << FRAC_BITS) - sum(q)
    q[max(range(TAPS), key=lambda i: abs(c[i]))] += err
    rows.append(q)

depth = len(rows) * TAPS
abits = max(1, math.ceil(math.log2(depth)))
here = os.path.dirname(os.path.abspath(__file__))
out = os.path.join(here, "..", "..", "target", "pocket", "audio_resampler_coefs.sv")

with open(out, "w") as f:
    f.write("// AUTO-GENERATED by support/audio/gen_resampler_coefs.py. Do not edit.\n")
    f.write(f"// Kaiser windowed sinc: {TAPS} taps, {PHASES} phases (0..{PHASES//2} stored), "
            f"cutoff {CUTOFF} * fs_in, beta {BETA}, signed Q2.{FRAC_BITS}\n")
    f.write("module audio_resampler_coefs (\n")
    f.write("    input wire clk,\n")
    f.write(f"    input wire [{abits-1}:0] addr,\n")
    f.write(f"    output reg signed [{WIDTH-1}:0] q\n);\n")
    f.write("  always @(posedge clk) begin\n    case (addr)\n")
    for p, row in enumerate(rows):
        for k, v in enumerate(row):
            a = p * TAPS + k
            v &= (1 << WIDTH) - 1
            f.write(f"      {abits}'d{a}: q <= {WIDTH}'h{v:05X};\n")
    f.write(f"      default: q <= {WIDTH}'h0;\n    endcase\n  end\nendmodule\n")
print(f"wrote {out}: {depth} coefficients, {abits}-bit address")
